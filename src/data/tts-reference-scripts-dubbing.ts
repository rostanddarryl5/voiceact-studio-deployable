function beat(
  id: string,
  tags: string[],
  text: string,
  intent: string,
  targetWpm: number,
  relativeRate: number,
  intensity: TtsDirectionBeat["intensity"],
  pitchContour: TtsDirectionBeat["pitchContour"],
  pauseAfterMs: number,
  visualScale: number,
  accelerate: boolean,
  scoringFocus: TtsSkill[],
): TtsDirectionBeat {
  return {
    id, tags, text, intent, targetWpm, relativeRate, intensity, pitchContour,
    pauseAfterMs, visualScale, accelerate, scoringFocus,
  };
}

